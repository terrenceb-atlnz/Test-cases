def rebootDutWithLimit(testCase, dut, disableTeardownDeconfigureOnBootFailure=True):
    success = True
    dut.log('')
    dut.log(['', '========= Long Run Action Start =========', ''])
    testCase.log(['', '-' * 80, '', 'Reboot {} with configured limit'.format(dut)])
    testCase.log('...save the running configuration')
    dut.mode('#')
    output = dut.cmd('wr')
    if 'Kernel' in output:
        success = False
        testCase.failed('{} kernel unstable writing configuration file'.format(dut))
        testCase.log(output)
        abortRebootDutWithLimit(testCase, dut, disableTeardownDeconfigure=disableTeardownDeconfigureOnBootFailure)
    else:
        testCase.log('...reboot, watch for successful or failed bootup')
        goodKeywords = ['done!', 'login:']
        badKeywords = ['panic', 'Watchdog timeout']
        dut.mode('#')
        output = dut.send('reboot\n')
        output = dut.send('y\n', strList=goodKeywords + badKeywords, waitTime=7200)
        if any(badKeyword in output for badKeyword in badKeywords):
            success = False
            seenKeywords = [badKeyword for badKeyword in badKeywords if badKeyword in output]
            testCase.failed('Saw bad output during bootup: "{}"'.format('", "'.join(map(str, seenKeywords))))
            testCase.log(output)
            abortRebootDutWithLimit(testCase, dut, disableTeardownDeconfigure=disableTeardownDeconfigureOnBootFailure)
        elif any(goodKeyword in output for goodKeyword in goodKeywords):
            testCase.passed('{} appears to have booted without failure'.format(dut))
        else:
            testCase.log('Did not see bootup complete on {}, attempt to log in and continue'.format(dut))

        coreFileList = []
        try:
            dut.mode('#', timeOut=900)
            coreFileList = check_and_wait_for_core_files(dut)
        except Exception as e:
            success = False
            testCase.failed('Exception thrown trying to communicate with DUT after reboot: {}'.format(e))
            abortRebootDutWithLimit(testCase, dut, disableTeardownDeconfigure=disableTeardownDeconfigureOnBootFailure)
            dut.mode('#', timeOut=900)
            coreFileList = check_and_wait_for_core_files(dut)
        if coreFileList:
            testCase.failed('Core files seen on {} : {}'.format(dut, ', '.join(map(str, coreFileList))))
        else:
            testCase.passed('No core files seen on {}'.format(dut))

        if success:
            testCase.testSet.wait_for_all_ports_running(msg='Wait for all ports to reach running state after mid-test reboot')

        testCase.log('')
        dut.log(['', '========= End of Long Run Action =========', ''])
    return success


