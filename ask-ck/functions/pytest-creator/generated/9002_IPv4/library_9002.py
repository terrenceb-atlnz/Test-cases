def replyArpRequest(ethIntToSendArpReply, timeout=5, pktCountToListen=1):
    pktList = sniff(iface=ethIntToSendArpReply, filter='arp', timeout=timeout, count=pktCountToListen)
    numRequests = 0
    for pkt in pktList:
        if pkt.haslayer(ARP):
            if pkt.op == 1:
                arpSenderMac = pkt.src
                targetIp = pkt.pdst
                numRequests = numRequests + 1
                sendArpUc(ethIntToSendArpReply, dstMac=arpSenderMac, arpSenderIp=targetIp)
    return numRequests


