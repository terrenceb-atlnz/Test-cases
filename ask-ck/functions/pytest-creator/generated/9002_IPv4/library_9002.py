class MultiTcpdump:
    '''
    Accepts 2 args on instantiation:
        tb:				ATTestBox object on which to start tcpdump processes
        ifaces:			list of interfaces, expected format is same as testSet.tbEthList
    Returns control once tcpdumps have been started on all the interfaces in the list

    stop_capture(timeout)    Call this method to stop all the tcpdump subprocesses after the timeout period 
                            and return a merged tcpdump output from all interfaces via stdout, stderr
    '''

    def __init__(self, tb, ifaces=[]):
        self.tb = tb                # tb to perform captures
        self.pcapProcs = {}         # dictionary with iface:subproc pairs
        self.pcapFiles = []
        if type(ifaces) != list:
            ifaces = [ifaces]

        for iface in ifaces:
            self.pcapProcs[iface] = self.tb.start_tcpdump(iface, f'{iface}.pcap', 'arp')
            self.pcapFiles.append(self.pcapProcs[iface].FILE_NAME)

    def stop_capture(self, timeout=0):
        time.sleep(timeout)

        for proc in self.pcapProcs.values():
            self.tb.stop_tcpdump(proc, delay=0)

        self.tb.cmd(f'mergecap -w /tmp/merged.pcap {" ".join(map(str, self.pcapFiles))}')
        stdout, stderr = self.tb.cmd('tcpdump -nnr /tmp/merged.pcap')

        return stdout, stderr


