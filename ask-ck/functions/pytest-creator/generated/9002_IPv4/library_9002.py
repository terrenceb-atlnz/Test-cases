def flip_port_to_garp(dut, tb, portList, ethList, gratArpLinkTime=None, capturePeriod=10, downPeriod=10, logOwner=None):
    portList = portList if isinstance(portList, list) else [portList]
    ethList = ethList if isinstance(ethList, list) else [ethList]

    log = logOwner.log if logOwner and hasattr(logOwner, "log") else None

    dut.mode(')#')
    if gratArpLinkTime is not None:
        dut.cmd(f'ip gratuitous-arp-link {gratArpLinkTime}')

    portsString = ','.join(str(port) for port in portList)

    tcpdumps = MultiTcpdump(tb, ifaces=ethList)
    if log:
        log(f'Toggle {portsString} port state down for {downPeriod} seconds')
    dut.cmd(f'int {portsString}')
    dut.cmd('shutdown')
    time.sleep(downPeriod)

    dut.cmd('no shutdown')

    inRunningState = False
    timeOut = 60
    timeOutAfter = time.time() + timeOut
    checkCount = 0

    if log:
        log(f'Waiting up to {timeOut} seconds for {portsString} to return to running state')

    portUpTime = None
    while not inRunningState and time.time() < timeOutAfter:
        time.sleep(1)
        checkCount += 1
        inRunningState = True
        output = dut.cmd('do show interface brief | grep running')
        for portString in portList:
            if f'{portString} ' not in output:
                inRunningState = False
            else:
                portUpTime = time.time()

    if inRunningState:
        if log:
            log(f'{portsString} now in running state')
        if portUpTime:
            if log:
                log(f'Port up timestamp: {datetime.fromtimestamp(portUpTime).strftime("%H:%M:%S.%f")}')
    else:
        if log:
            log(f'{portsString} still not in running state')
            log(output)

    stdout, stderr = tcpdumps.stop_capture(timeout=capturePeriod)

    return stdout, stderr


