def traffic_test(tb, srcInt, srcMAC, srcIP, dstInt, dstMAC, dstIP, ipVer=4, encap=None, vlan=1, numPkts=1000, expectReceive=True, maxTry=3):
    """
    tb      	: TestBox object
    srcInt  	: Interface to transmit the packets from
    srcMAC  	: MAC address to be used as the source MAC address
    srcIP  		: IP address to be used as the source IP address
    dstInt 		: Interface to capture packets on
    dstMAC 		: MAC address to be used as the destination MAC adddress
    dstIP  		: IP address to be used as the destination IP address
    ipVer   	: 4 or 6
    encap   	: 'Dot1Q' or None
    numPkts 	: Total number of packets to transmit
    expectReceive	: True if all packetes are exepected to be received, False if no packets are expected to be received
    maxTry  	: Number of tries before concluding that something is wrong
    """
    DPORT = 60606

    if ipVer == 4:
        ipLayer = IP(src=srcIP, dst=dstIP)
    else:
        ipLayer = IPv6(src=srcIP, dst=dstIP)

    if encap == 'Dot1Q':
        pkts = Ether(src=srcMAC, dst=dstMAC) / Dot1Q(vlan=vlan) / ipLayer / UDP(sport=range(numPkts), dport=DPORT)
    else:
        pkts = Ether(src=srcMAC, dst=dstMAC) / ipLayer / UDP(sport=range(numPkts), dport=DPORT)

    passed = False
    for tryNum in range(maxTry):
        # tcpdump fails to match on "dst port DPORT" if the packet is encapsulated in PPPoE.
        # Just capture all packets then use scapy to sort through all captured packets.
        tcpdump = tb.start_tcpdump(dstInt, 'tmp.pcap')
        sendp(pkts, iface=srcInt, verbose=False, inter=1.0 / numPkts)
        recPkts = tb.stop_tcpdump(tcpdump)
        numRecvPkts = 0
        for pkt in recPkts:
            if pkt.haslayer(ipLayer.__class__):
                if pkt.getlayer(ipLayer.__class__).src == srcIP and pkt.getlayer(ipLayer.__class__).dst == dstIP:
                    numRecvPkts = numRecvPkts + 1
        if (expectReceive) and (numRecvPkts == numPkts):
            passed = True
            break
        if (not expectReceive) and (numRecvPkts == 0):
            passed = True
            break
    return passed


