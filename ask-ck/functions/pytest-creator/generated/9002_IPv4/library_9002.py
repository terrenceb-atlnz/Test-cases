# selected because it uses ping to test IP connectivity from a device, reusable for pinging
# the loopback from the DUT and checking 0% loss (or 100% loss after removal).
def ping_check(testCase, swi, ipAddress, expectResponse=True, allowLoss=True, count=None):
   '''
   Use ping to test IP connectivity from a device

   Parameters:
   testCase       : the test case object
   swi            : the device to ping from
   ipAddress      : the IP address to ping
   expectResponse : if True, fail if no response is received; if False, fail if any response is received
   allowLoss      : if True and expectResponse, pass if any response is received; if False and expectResponse, fail if any pings fail
   count          : optionally specify the number of pings to send

   Returns: True if ping response is as expected, False otherwise
   '''
   success = False
   swi.mode('#')
   if count:
      output = swi.cmd('ping {} repeat {}'.format(ipAddress, count))
   else:
      output = swi.cmd('ping {}'.format(ipAddress))

   if expectResponse:
      if allowLoss:
         if 'packets transmitted' in output and ' 100% packet loss' not in output:
            testCase.passed('{} was able to ping {}'.format(swi.name, ipAddress))
            success = True
         else:
            testCase.failed('{} failed to ping {}'.format(swi.name, ipAddress))
            testCase.log(output)
      else:
         if 'packets transmitted' in output and ' 0% packet loss' in output:
            testCase.passed('{} was able to ping {}'.format(swi.name, ipAddress))
            success = True
         else:
            testCase.failed('{} failed to ping {} 100%'.format(swi.name, ipAddress))
            testCase.log(output)
   else:
      if ' 100% packet loss' in output or 'packets transmitted' not in output:
         testCase.passed('{} was unable to ping {}'.format(swi.name, ipAddress))
         success = True
      else:
         testCase.failed('{} unexpectedly received response from {}'.format(swi.name, ipAddress))
         testCase.log(output)

   return success


