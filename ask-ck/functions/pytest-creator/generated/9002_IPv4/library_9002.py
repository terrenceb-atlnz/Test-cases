def word_count(sentence, word_to_count):
    counts = dict()
    words = sentence.split()
    for word in words:
        if word in counts:
            counts[word] += 1
        else:
            counts[word] = 1
    if word_to_count in counts:
        return counts[word_to_count]
    else:
        return 0


