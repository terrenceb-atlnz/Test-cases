# capture and for per-port status checks (match by port name, test not 'connected'); adapt for
# the baseline and link-state checks.
def parseShowIntStatus(showIntStatus):
	'''
	Converts show int status into a dict
	:param str showIntStatus: unmodified output of a show int status command
	:ret {"str":(str,str,int,str,int,str)} intStatusDict:
		port is the key, eg port1.0.2, data is a tuple of the following
		name, status, vlan, duplex, speed, type
	'''
	#showIntStatus = showIntStatus[showIntStatus.rindex("Type       \r\n")+len("Type       \r\n"):].splitlines()
	#showIntStatus = showIntStatus[showIntStatus.rindex("Type\r\n")+len("Type\r\n"):].splitlines()

	ref1 = re.search('Port(.*)Name(.*)Status(.*)Vlan(.*)Duplex(.*)Speed(.*)Type(.*)\r\n', showIntStatus)
	ref2 = re.search('\r\n', showIntStatus [ref1.start():])
	index = ref1.start() + ref2.start() +2   # +2 since \r and \n each are worth 1 character
	showIntStatus = showIntStatus[index:].splitlines() 
	intStatusDict = {}
	for line in showIntStatus:
		if "Name " in line:
			continue
		if "------" in line:
			continue
		if "More" in line:
			continue
		if "#" in line:
			break

		port = line[0:11].strip()
		name = line[11:30].strip()
		status = line[30:48].strip()
		vlan = line[48:53].strip()
		duplex = line[53:60].strip()
		speed = line[60:68].strip()
		type = line[68:].strip()

		intStatusDict[port] = (name,status,vlan,duplex,speed,type)

	# import pandas as pd
	# show_int_status_dict = libSvt.parseShowIntStatus(interfaces_status)
	# sisDF = pd.DataFrame(show_int_status_dict).transpose()
	# port_list = list(show_int_status_dict.keys())
	# connected = sisDF[sisDF[1] == "connected"][0].index.tolist()
	# disconnected = sisDF[sisDF[1] != "connected"][0].index.tolist()
	return intStatusDict


