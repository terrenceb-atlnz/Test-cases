class traffic_sniffer():

    def __init__(self, interface, filter=" ", timeout=10, count=1):
        """
        Creates packet caputure
        filter - tcpdump filter string
        interface - interface to capture traffic on
        timeout - how long the caputure will run for
        count - amount of packets to capture
        """

        self.interface = interface
        self.filter = filter
        self.timeout = timeout
        self.count = count

    def _packet_capture(self):

        if self.filter == " ":
            cap = sniff(count=self.count, iface=self.interface, filter=self.filter, timeout=self.timeout)
            self.send_end.send(cap)

        else:
            cap = sniff(count=self.count, iface=self.interface, filter=self.filter, timeout=self.timeout)
            self.send_end.send(cap)

    def start_capture(self):
        """
        Start the scapy packet capture.

        Return the process object
        """
        self.pipe_list = []
        self.recv_end, self.send_end = multiprocessing.Pipe(False)

        p = multiprocessing.Process(target=self._packet_capture)
        self.pipe_list.append(self.recv_end)
        p.start()

        time.sleep(0.1)

        self.capture_process = p

    def end_capture(self):
        """
        End the capture process and return the packet.
        """

        self.capture_process.join()
        result = [x.recv() for x in self.pipe_list]
        packet_list = result[0]

        if len(packet_list) == 0: # Check if a packet is present in the list
            return False

        return packet_list[0]


