# AI: dependency `GarpPacket` of # ART 1351_gratuitous_arp/test-1351.1001.py lines 526-609
class GarpPacket:
    def __init__(self, line=False):
        if line:
            self.init_time(line)
            self.init_ip(line)

    def init_time(self, line):
        line = line.split()
        self.timeReceived = line

    def init_ip(self, line):
        self.hostIP = ''
        self.tellIP = ''
        self.mac = ''

    def get_time_diff(self, garppacket):
        timeA = self.timeReceived[0]
        timeB = garppacket.timeReceived[0]
        fmt = '%H:%M:%S.%f'
        tdelta = datetime.strptime(timeA, fmt) - datetime.strptime(timeB, fmt)
        seconds = int(round(tdelta.total_seconds(), 0))

        return seconds

    def compare_time(self, allowedtime, garppacket):
        timeDiff = self.get_time_diff(garppacket)

        if timeDiff >= allowedtime[0] and timeDiff <= allowedtime[1]:
            return True
        return False

    def get_time(self):
        timeA = self.timeReceived[0]

        return timeA

    def get_host_ip(self):
        return self.hostIP
