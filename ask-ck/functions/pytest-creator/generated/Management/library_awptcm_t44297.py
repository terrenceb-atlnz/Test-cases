# selected to decode the captured LLDPDU and prove at least one LLDPDU from the test port is
# decodable.
def analyse_lldp_packets(self, recPktList):
    lldp_med_packets = []
    for idx, pkt in enumerate(recPktList):
        self.log(f'Analyzing packet {idx + 1}:')
        if pkt.haslayer(lldp_basic):
            self.log('  Packet has lldp_basic layer')
            self.log(f'  Chassis ID: {pkt[lldp_basic].chassis_id}')
            self.log(f'  Port ID: {pkt[lldp_basic].port_id}')
            self.log(f'  TTL: {pkt[lldp_basic].ttl_val}')

            if pkt.haslayer(lldp_base_cap_tlv):
                self.log('  Packet has base capabilities TLV')
            else:
                self.log('  Packet is missing base capabilities TLV')

            if pkt.haslayer(lldp_cap_tlv):
                self.log('  Packet has LLDP-MED capabilities TLV')
                self.log(f'  MED Capabilities: {pkt[lldp_cap_tlv].lldp_med_cap}')
                self.log(f'  Device Type: {pkt[lldp_cap_tlv].lldp_med_dev}')
                lldp_med_packets.append(pkt)
            else:
                self.log('  Packet is missing LLDP-MED capabilities TLV')

            if pkt.haslayer(lldp_power_tlv):
                self.log('  Packet has power management TLV')
                self.log(f'  Power Value: {pkt[lldp_power_tlv].lldp_power_val}')
            else:
                self.log('  Packet is missing power management TLV')

            if pkt.haslayer(lldp_uuid_tlv):
                self.log('  Packet has UUID TLV')
                self.log(f'  UUID: {pkt[lldp_uuid_tlv].lldp_uuid}')

            self.log(f'  All layers: {pkt.layers()}')
        else:
            self.log('  Packet does not have lldp_basic layer')

        self.log(f'  Full packet details:\n{pkt.show(dump=True)}')


