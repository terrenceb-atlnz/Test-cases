# selected to confirm LLDP is running and the partner records neighbour information from the
# test port.
def parse_lldp_neighbours(self, swi, swiMacAddrCisco, output, linksDict):
    if swiMacAddrCisco not in list(linksDict.keys()):
        linksDict[swiMacAddrCisco] = {}
    lines = output.split('\n')
    swiPortRange = swi.get_all_ports()
    lineIndex = 0
    while lineIndex < len(lines):
        line = lines[lineIndex]
        parts = line.strip().split()
        if parts and 'port{}'.format(parts[0]) in swiPortRange:
            break
        lineIndex += 1
    while lineIndex < len(lines):
        line = lines[lineIndex].strip()
        parts = line.strip().split()
        if parts:
            if 'port{}'.format(parts[0]) not in swiPortRange:
                break
        else:
            break
        localPort = parts[0]
        if '.' in localPort:
            localPort = 'port{}'.format(localPort)
        peerMac = parts[1]
        peerPort = parts[2]
        linksDict[swiMacAddrCisco][localPort] = [peerMac, peerPort]
        lineIndex += 1
    return linksDict


