# selected to record the LLDP/port frame counters before and after the change sequence.
def getPortCo(dut, portSelection = '', addToLog = False, interface = False):
	'''
	:param framework.ATDrivers.ATSwitch dut: switch that has port counters, must be in "# mode."
	:param str portList: list of ports to get counters from. In standard port
		selection notation, eg port1.0.1-1.0.6,port1.0.7,port1.0.8.
		If portSelection is '' get all port counters.
	:param bool addToLog: set to true to include the cmd output to the swi log
	:param bool interface: set to true to log show interface instead of
		show platform port counter. portSelection can still be used.
	:ret str portCo: output of the show command
	'''
	if interface:
		if len(portSelection) == 0:
			portCo = dut.cmd("show interface", log=addToLog)
		else:
			portCo = dut.cmd("show interface {}".format(portSelection), log=addToLog)

	else:
		if len(portSelection) == 0:
			portCo = dut.cmd("show platform port counter", log=addToLog)
		else:
			portCo = dut.cmd("show platform port {} counter".format(portSelection), log=addToLog)
	return portCo
