# selected to bring up and confirm the physical link on the test port before verifying show
# interface status connected.
def wait_for_port_link_up(testCase, dut, portList, timeOut=30, log=True):
    if log:
        log = testCase.log
    else:
        log = __dev_null

    dut.mode('#')
    initTime = time.time()
    timeOutAt = initTime + timeOut
    portsUp = False
    while time.time() < timeOutAt:
        ready = True
        for port in portList:
            if type(port) is Eth:
                if port.is_up() == False:
                    ready = False
                    break
            else:
                output = dut.cmd('show interface {}'.format(port.name))
                if not ('RUNNING' in output):
                    ready = False
                    break
        if ready:
            portsUp = True
            log('Ports are now running')
            break
    return portsUp


