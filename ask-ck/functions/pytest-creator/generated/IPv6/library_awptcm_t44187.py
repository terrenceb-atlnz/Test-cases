def expect_service_blocked(testcase, service_name, tcp_ports=None, udp_ports=None):
    dutA = testcase.testSet.dutA
    tb = testcase.testSet.tb
    ethA_ipv4 = tb.ethA.get_ipv4_addr(2)
    ethA_ipv6 = tb.ethA.get_ipv6_addr(2)

    target_ports = []
    if tcp_ports:
        target_ports.extend(tcp_ports)
    if udp_ports:
        target_ports.extend(udp_ports)

    if not target_ports:
        testcase.log(f"{service_name}: No ports specified for blocking verification")
        return

    testcase.log(f"Verifying {service_name} ports are blocked: {target_ports}")

    scanResult, consoleOutput, logFailures, permanentLogFailures = run_port_scan_on_device(
        self=testcase,
        dut=dutA,
        tb=tb,
        targetPortList=target_ports,
        monitorConsole=False,
        checkLogs=False,
        splitPorts=False,
        ipv4AddressList=[ethA_ipv4],
        ipv6AddressList=[ethA_ipv6]
    )

    blocked_ports = []
    still_open_ports = []

    if scanResult:
        for scan_key, scan_data in scanResult.items():
            for ip_addr, host_data in scan_data.items():
                ip_version = 'IPv6' if ':' in ip_addr else 'IPv4'

                if tcp_ports and 'tcp' in host_data:
                    for port in tcp_ports:
                        if port in host_data['tcp']:
                            state = host_data['tcp'][port].get('state', 'unknown')
                            port_info = f"TCP {port} ({ip_version})"
                            if state == 'open':
                                still_open_ports.append(port_info)
                            else:
                                blocked_ports.append(f"{port_info}: {state}")
                        else:
                            blocked_ports.append(f"TCP {port} ({ip_version}): not detected")

                if udp_ports and 'udp' in host_data:
                    for port in udp_ports:
                        if port in host_data['udp']:
                            state = host_data['udp'][port].get('state', 'unknown')
                            port_info = f"UDP {port} ({ip_version})"
                            if state == 'open':
                                still_open_ports.append(port_info)
                            else:
                                blocked_ports.append(f"{port_info}: {state}")
                        else:
                            blocked_ports.append(f"UDP {port} ({ip_version}): not detected")
    else:
        for port in (tcp_ports or []):
            blocked_ports.append(f"TCP {port}: no response")
        for port in (udp_ports or []):
            blocked_ports.append(f"UDP {port}: no response")

    if still_open_ports:
        testcase.failed(f'{service_name}: Expected blocked, but still open: {still_open_ports}')
    else:
        testcase.passed(f'{service_name}: All ports properly blocked ({blocked_ports})')


