def monitor_logs_for_continued_change(self, swi, minutes=10):
    waitOnFailureMinutes = minutes
    waitCyclePeriod = 30
    oldLog = get_show_log(swi)
    oldPermanentLog = get_show_log_permanant(swi)

    if swi.get_stack():
        devName = swi.get_stack().name
    else:
        devName = swi.name

    self.log(['', 'Device appears to have failed the port-scan test'])
    self.log('Monitor device for continued failure for {} minutes'.format(waitOnFailureMinutes))
    self.log('')
    memoryDataPointId = 1
    memoryData = ATMemory.MemoryData(swi, log=swi.log)
    memoryData.record_memory_data_point_for_all_processes(dataPointId=memoryDataPointId)
    log_memory(self, swi)
    timeOutAt = time.time() + (waitOnFailureMinutes * 60)
    while time.time() < timeOutAt:
        time.sleep(waitCyclePeriod)
        memoryDataPointId += 1
        memoryData.record_memory_data_point_for_all_processes(dataPointId=memoryDataPointId)
        log_memory(self, swi)
        newLog = get_show_log(swi)
        newPermanentLog = get_show_log_permanant(swi)
        changedLogs = compare_logs(oldLog, newLog)
        changedPermanentLogs = compare_logs(oldPermanentLog, newPermanentLog)
        if changedLogs:
            self.log(['', 'New log entries since last check:'])
            self.log(['   {}'.format(x) for x in changedLogs])
        if changedPermanentLogs:
            self.log(['', 'New permanent log entries since last check:'])
            self.log(['   {}'.format(x) for x in changedPermanentLogs])
        log_memory(self, swi)
        oldLog = newLog
        oldPermanentLog = newPermanentLog

    commonId = '{}_{}_{}_{}'.format(self.testCaseName, swi.softVer, devName, time.time())
    memorySizeLeak, memoryVirtLeak = memoryData.get_processes_with_increasing_memory()
    if memorySizeLeak:
        fileName = 'memory_{}_size.csv'.format(commonId)
        self.failed('Possible memory size leaks found in processes on {}'.format(devName))
        self.log('...please review memory consumption data exported to {}'.format(fileName))
        self.log('\n{}'.format(pprint.pformat(memorySizeLeak)))
        memoryData.export_csv_memory_size_data_for_processes(list(memorySizeLeak.keys()), fileName=fileName, combineStackMembers=False)
    if memoryVirtLeak:
        fileName = 'memory_{}_virtual.csv'.format(commonId)
        self.failed('Possible virtual memory leaks found in processes on {}'.format(devName))
        self.log('...please review memory consumption data exported to {}'.format(fileName))
        self.log('\n{}'.format(pprint.pformat(memoryVirtLeak)))
        memoryData.export_csv_memory_virtual_data_for_processes(list(memoryVirtLeak.keys()), fileName=fileName, combineStackMembers=False)


