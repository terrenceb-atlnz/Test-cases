# second valid user and the account to be disabled later with known credentials.
def generate_dict_of_usernames_and_passwords(num=10, usernameLength=8, passwordLength=12):
    userSet = set()
    passwordSet = set()
    userDict = {}
    while len(userSet) < num:
        userSet.add(''.join(random.choice(string.ascii_lowercase + string.ascii_uppercase) for _ in range(usernameLength)))
    while len(passwordSet) < num:
        passwordSet.add(''.join(random.choice(string.ascii_lowercase + string.ascii_uppercase) for _ in range(passwordLength)))
    userList = list(userSet)
    passwordList = list(passwordSet)
    for i in range(0, num):
        userDict[userList[i]] = passwordList[i]
    return userDict


