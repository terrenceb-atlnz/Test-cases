# reuse to issue `show privilege`/`show system` and assert no authentication or authorisation
# error text.
def send_shell_command(shell, command, timeout=10, log_func=None):
    if log_func:
        log_func(f'SSH shell> {command}')

    while shell.recv_ready():
        try:
            shell.recv(8192)
        except Exception:
            break

    shell.send(f'{command}\r')

    output_buffer = ""
    end_time = time.time() + timeout
    stable_count = 0

    while time.time() < end_time:
        if shell.recv_ready():
            try:
                chunk = shell.recv(4096).decode('utf-8', errors='ignore')
                if chunk:
                    output_buffer += chunk
                    stable_count = 0
                    while shell.recv_ready():
                        try:
                            more_chunk = shell.recv(4096).decode('utf-8', errors='ignore')
                            if more_chunk:
                                output_buffer += more_chunk
                            else:
                                break
                        except Exception:
                            break
                        time.sleep(0.01)

            except Exception as e:
                if output_buffer.strip():
                    break
                error_msg = f"Error reading from shell: {str(e)}"
                if log_func:
                    log_func(f'SSH shell< ERROR: {error_msg}')
                return error_msg
        else:
            stable_count += 1

        if '--More--' in output_buffer:
            output_buffer = handle_pagination(shell, output_buffer, timeout)

        if output_buffer.strip():
            lines = output_buffer.strip().split('\n')
            if lines and any(prompt in lines[-1] for prompt in ['#', '>', '$', ')#', 'password:']):
                if stable_count >= 5:
                    break

        time.sleep(0.1)

    ansi_escape = re.compile(r'\x1B(?:[@-Z\\-_]|\[[0-?]*[ -/]*[@-~])')
    clean_output = ansi_escape.sub('', output_buffer)
    clean_output = re.sub(r'\^\[\[\d+;\d+R', '', clean_output)

    if log_func:
        log_func(f'SSH shell< {clean_output}')
    return clean_output.strip()


