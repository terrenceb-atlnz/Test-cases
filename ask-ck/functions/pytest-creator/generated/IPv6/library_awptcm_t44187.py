def remote_connect_test(log, protocol, serverAddr, user = None, passwd = None, retries = 1):
    if protocol == 'ssh':
        ssh = paramiko.SSHClient()
        retry = 0
        success = False
        while (not success) and (retry < retries):
            ssh.set_missing_host_key_policy(paramiko.AutoAddPolicy())
            try:
                ssh.connect(serverAddr, username = user, password = passwd, timeout = 5)
                log('SSH connection successfully opened')
                success = True
            except Exception as e:
                log('SSH connect exception: {}'.format(e))
                retry += 1
                time.sleep(5)
        if (retry >= retries):
            log('UNABLE TO CONNECT VIA SSH')
        ssh.close()
    elif protocol == 'telnet':
        telnet = telnetlib.Telnet()
        retry = 0
        success = False
        while (not success) and (retry < retries):
            try:
                telnet.open(serverAddr, timeout = 5)
                log('Telnet connection successfully opened')
                success = True
            except Exception as e:
                log('Telnet connect exception: {}'.format(e))
                retry += 1
                time.sleep(5)
        if (retry >= retries):
            log('UNABLE TO CONNECT VIA TELNET')
        telnet.close()
    else:
        log('remote_login_test(): unknown protocol')

    return success


