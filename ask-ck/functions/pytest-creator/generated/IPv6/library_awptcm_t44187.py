def connect_via_ssh(self, sshServer, username='manager', password='friend', key_filename=None, expect_failure=False):
    retry = 0
    max_retries = 5 if not expect_failure else 1  # Only try once if we expect failure
    sshConnected = False

    ssh = paramiko.SSHClient()
    ssh.set_missing_host_key_policy(paramiko.AutoAddPolicy())

    auth_method = 'public key' if key_filename else 'password'
    self.log(f'Using {auth_method} authentication for SSH connection')

    while (not sshConnected) and (retry < max_retries):
        try:
            self.log(f'SSH connection attempt {retry + 1}')

            if key_filename:
                ssh.connect(
                    sshServer,
                    username=username,
                    key_filename=key_filename,
                    timeout=30
                )
            else:
                ssh.connect(sshServer, username=username, password=password, timeout=30)

            sshConnected = True
            self.log('SSH connection successful')
        except Exception as e:
            self.log(f'SSH connection attempt {retry + 1} failed: {str(e)}')
            retry += 1
            if retry < max_retries:
                time.sleep(5)

    if expect_failure:
        if sshConnected:
            self.failed(f'SSH connection as {username} using {auth_method} succeeded when failure was expected')
            return None
        else:
            self.passed(f'SSH connection as {username} using {auth_method} correctly failed as expected')
            return None
    else:
        if (retry >= max_retries):
            self.failed(f'UNABLE TO CONNECT VIA SSH as {username} using {auth_method} after {max_retries} attempts')
            return None

        self.passed(f'Successfully connected via SSH as {username} using {auth_method}')
        return ssh


