# selected because it drives paged CLI output to completion over a remote session — essential
# for capturing the last line of long paged outputs without mid-line truncation.
def handle_pagination(shell, output_buffer, timeout=10):
    end_time = time.time() + timeout
    last_output_time = time.time()

    while time.time() < end_time:
        if '--More--' in output_buffer:
            shell.send(' ')
            time.sleep(0.3)
            last_output_time = time.time()

            additional_timeout = time.time() + 5
            while time.time() < additional_timeout:
                if shell.recv_ready():
                    try:
                        chunk = shell.recv(4096).decode('utf-8', errors='ignore')
                        output_buffer += chunk
                        last_output_time = time.time()
                        break
                    except Exception:
                        break
                time.sleep(0.1)
        else:
            lines = output_buffer.strip().split('\n')
            if lines and any(prompt in lines[-1] for prompt in ['#', '>', '$']):
                output_buffer = re.sub(r'--More--\s*', '', output_buffer)
                return output_buffer
            else:
                if shell.recv_ready():
                    try:
                        chunk = shell.recv(4096).decode('utf-8', errors='ignore')
                        output_buffer += chunk
                        last_output_time = time.time()
                    except Exception:
                        pass
                elif time.time() - last_output_time > 3:
                    break
                time.sleep(0.1)

    output_buffer = re.sub(r'--More--\s*', '', output_buffer)
    return output_buffer


